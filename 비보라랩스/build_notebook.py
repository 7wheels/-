    # Adobe 한글 CID 폰트에는 U+00B7(·) 글리프가 없어 누락됨 → U+318D(ㆍ, 정상 렌더)로 치환
    def _fix(o):
        if isinstance(o, str):
            return o.replace("·", "ㆍ")
        if isinstance(o, dict):
            return {k: _fix(v) for k, v in o.items()}
        if isinstance(o, (list, tuple)):
            return type(o)(_fix(x) for x in o)
        return o
    META, PRINCIPLE, MONTHS = _fix(globals()["META"]), _fix(globals()["PRINCIPLE"]), _fix(globals()["MONTHS"])
