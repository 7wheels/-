            L.append("**□ 실험 방법 / 조건**")
            for x in e["method"]:
                L.append(f"- {x}")
            L.append("")
            L.append("**□ 실험 결과 / 데이터**\n")
            for blk in e["result"]:
                if blk[0] == "p":
                    L.append(blk[1] + "\n")
                else:
                    _, cap, headers, rows = blk
                    L.append(f"*{cap}*\n")
                    L.append("| " + " | ".join(headers) + " |")
